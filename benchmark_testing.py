from __future__ import annotations
import json
import math
import time
from pathlib import Path
from typing import Callable, List, Tuple
from evolution import evolve_vector

# Benchmark functions
def rastrigin(x: List[float]) -> float:
    """
    Rastrigin function — global minimum 0 at the origin.
    """
    n = len(x)
    A = 10.0
    return A * n + sum(xi**2 - A * math.cos(2 * math.pi * xi) for xi in x)


def rosenbrock(x: List[float]) -> float:
    """
    Rosenbrock (banana) function — global minimum 0 at (1, 1, ..., 1).
    """
    return sum(
        100.0 * (x[i + 1] - x[i] ** 2) ** 2 + (1.0 - x[i]) ** 2
        for i in range(len(x) - 1)
    )

def evolve(
    objective: Callable[[List[float]], float],
    n_dims: int,
    lo: float,
    hi: float,
    population_size: int = 40,
    max_evaluations: int = 20_000,
    mutation_sigma: float = 0.08,
    seed: int = 42,
) -> Tuple[List[float], float, List[float]]:
    return evolve_vector(
        objective=objective,
        n_dims=n_dims,
        lo=lo,
        hi=hi,
        population_size=population_size,
        evaluations=max_evaluations,
        seed=seed,
        sigma=mutation_sigma,
    )

# ---------------------------------------------------------------------------
# Run and report -> this part is completely generated by AI
# ---------------------------------------------------------------------------

def run_benchmark(
    name: str,
    objective: Callable[[List[float]], float],
    n_dims: int,
    lo: float,
    hi: float,
    known_optimum: float,
    known_optimum_location: List[float],
    population_size: int = 50,
    max_evaluations: int = 30_000,
    n_runs: int = 5,
) -> dict:
    """Run the EA multiple times and report mean / best / worst results."""

    print(f"\n{'=' * 60}")
    print(f"  Benchmark : {name}")
    print(f"  Dims      : {n_dims}")
    print(f"  Bounds    : [{lo}, {hi}]")
    print(f"  Known min : {known_optimum}  at {known_optimum_location}")
    print(f"  Runs      : {n_runs}  |  Budget : {max_evaluations} evals each")
    print(f"{'=' * 60}")

    all_best_fitness: List[float] = []
    all_best_genes: List[List[float]] = []
    all_histories: List[List[float]] = []

    for run in range(n_runs):
        t0 = time.perf_counter()
        genes, fitness, history = evolve(
            objective=objective,
            n_dims=n_dims,
            lo=lo,
            hi=hi,
            population_size=population_size,
            max_evaluations=max_evaluations,
            seed=run * 31 + 7,   # different seed per run
        )
        elapsed = time.perf_counter() - t0

        all_best_fitness.append(fitness)
        all_best_genes.append(genes)
        all_histories.append(history)

        genes_str = ", ".join(f"{g:.4f}" for g in genes)
        print(f"  Run {run + 1}: fitness = {fitness:.6f}  "
              f"genes = [{genes_str}]  ({elapsed:.2f}s)")

    mean_f = sum(all_best_fitness) / n_runs
    best_f = min(all_best_fitness)
    worst_f = max(all_best_fitness)
    print(f"\n  Summary — mean: {mean_f:.6f}  best: {best_f:.6f}  worst: {worst_f:.6f}")

    # How far is the best solution from the known optimum location?
    best_run_idx = all_best_fitness.index(best_f)
    best_genes = all_best_genes[best_run_idx]
    dist_to_optimum = math.sqrt(
        sum((g - opt) ** 2 for g, opt in zip(best_genes, known_optimum_location))
    )
    print(f"  Distance from best solution to known optimum: {dist_to_optimum:.4f}")

    return {
        "benchmark": name,
        "n_dims": n_dims,
        "known_optimum": known_optimum,
        "known_optimum_location": known_optimum_location,
        "mean_fitness": mean_f,
        "best_fitness": best_f,
        "worst_fitness": worst_f,
        "best_genes": best_genes,
        "distance_to_optimum": dist_to_optimum,
        "histories": all_histories,
    }

def main() -> None:
    results = []

    # --- Rastrigin 2D ---
    results.append(run_benchmark(
        name="Rastrigin 2D",
        objective=rastrigin,
        n_dims=2,
        lo=-5.12,
        hi=5.12,
        known_optimum=0.0,
        known_optimum_location=[0.0, 0.0],
        population_size=50,
        max_evaluations=30_000,
        n_runs=5,
    ))

    # --- Rastrigin 10D (harder) ---
    results.append(run_benchmark(
        name="Rastrigin 10D",
        objective=rastrigin,
        n_dims=10,
        lo=-5.12,
        hi=5.12,
        known_optimum=0.0,
        known_optimum_location=[0.0] * 10,
        population_size=80,
        max_evaluations=50_000,
        n_runs=5,
    ))

    # --- Rosenbrock 2D ---
    results.append(run_benchmark(
        name="Rosenbrock 2D",
        objective=rosenbrock,
        n_dims=2,
        lo=-2.048,
        hi=2.048,
        known_optimum=0.0,
        known_optimum_location=[1.0, 1.0],
        population_size=50,
        max_evaluations=30_000,
        n_runs=5,
    ))

    # --- Rosenbrock 10D (harder) ---
    results.append(run_benchmark(
        name="Rosenbrock 10D",
        objective=rosenbrock,
        n_dims=10,
        lo=-2.048,
        hi=2.048,
        known_optimum=0.0,
        known_optimum_location=[1.0] * 10,
        population_size=80,
        max_evaluations=50_000,
        n_runs=5,
    ))

    # Save results to JSON for inspection
    out_path = Path("results/benchmark_results.json")
    out_path.parent.mkdir(exist_ok=True)
    out_path.write_text(json.dumps(results, indent=2), encoding="utf-8")
    print(f"\nResults saved to {out_path.resolve()}")

if __name__ == "__main__":
    main()